#!/usr/bin/env python3
"""
regen_tables.py — regenerate Paper-1 LaTeX tables from the rebuilt screen.

Sources: outputs/recompute/{screen_full.csv,summary.json,robustness.json} for the
candidate tables; the dataset CSV for the composition correlations (which the
Scharber recomputation cannot change, but which need CI and p per referees 2 and 4).

Emits, into tables/:
  tab_candidates.tex        the promoted molecules, all four conventions, with
                            the reason each is or is not a defensible candidate
  tab_conventions.tex       the four (absorber x FF) variants side by side:
                            pool, cascade, first place -- the convention-dependence
                            result (ledger L-2026-09-01-17)
  tab_correlations.tex      heteroatom-composition correlations + 95 % CI + p
  tab_model_settings.tex    every Scharber parameter, so the model is quotable

The submitted tab_top_candidates.tex is left on disk untouched; it is superseded
by tab_candidates.tex and its \\input is switched in the section file.

Run from the Paper-1 folder:  python regen_tables.py
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
REC = HERE / "outputs" / "recompute"
TABDIR = HERE / "tables"
TABDIR.mkdir(exist_ok=True)

# The corrected reorganization-energy table lives in the sibling NTO study in the
# working tree, and beside this script under data/ in the published deposit.
REORG = next((p for p in (HERE / "data" / "reorganization_energies_corrected.csv",
                          HERE.parent / "NTO_and_related_study" / "analysis" /
                          "reorganization_energies_corrected.csv") if p.exists()),
             HERE / "data" / "reorganization_energies_corrected.csv")

df = pd.read_csv(REC / "screen_full.csv")
summary = json.loads((REC / "summary.json").read_text())
robust = json.loads((REC / "robustness.json").read_text())

VARIANTS = [("strict_FF065", "strict, $FF = 0.65$"),
            ("strict_FFgreen", "strict, Green $n = 1$"),
            ("compl_FF065", "compl., $FF = 0.65$"),
            ("compl_FFgreen", "compl., Green $n = 1$")]
LEAD = 9168
QUINONE = {19598, 21736, 23450}
DYES = {22936}


def row(mid):
    return df.loc[df.mol_id == mid].iloc[0]


def fmt(x, nd=2, plus=False):
    if pd.isna(x):
        return "---"
    return f"{x:+.{nd}f}" if plus else f"{x:.{nd}f}"


