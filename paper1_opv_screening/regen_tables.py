def tab_candidates():
    ids = sorted(set(robust["union_all_variants"]) | {LEAD})
    verdict = {}
    for mid in ids:
        if mid in QUINONE:
            verdict[mid] = "\\emph{o}-quinone tautomer (R7)"
        elif mid in DYES:
            verdict[mid] = "anthraquinone dye"
        elif mid == LEAD:
            verdict[mid] = "\\textbf{defensible}"
        else:
            verdict[mid] = "---"

    lines = [
        "% Regenerated by regen_tables.py from outputs/recompute/screen_full.csv.",
        "% Ledger: L-2026-09-01-16, -17, -19, -20, -21.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Every molecule that is chemically valid, passes the stability screen and "
        "reaches $\\pcesascore > 0$ under at least one of the four modelling conventions of "
        "\\cref{tab:conventions}. Frontier energies are B3LYP/6-31G*//PM6; $\\pcesascore$ is "
        "quoted for the fixed fill factor ($FF = 0.65$) and, in parentheses, for the "
        "ideality-limited expression. Only molecule 9168 is positive under all four "
        "conventions. The final column records why the remaining entries are not defensible "
        "candidates despite clearing every numerical filter --- the point of "
        "\\cref{sec:results_r7}.}",
        "\\label{tab:candidates}",
        "\\begin{tabular}{lcccccccl}",
        "\\toprule",
        "ID & Formula & \\makecell{HOMO\\\\(\\unit{\\electronvolt})} & "
        "\\makecell{LUMO\\\\(\\unit{\\electronvolt})} & \\makecell{gap\\\\(\\unit{\\electronvolt})} & "
        "SAScore & \\makecell{PCE\\\\(\\unit{\\percent})} & $\\pcesascore$ & verdict \\\\",
        "\\midrule",
    ]
    # order: lead first, then by complementary score
    ordered = [LEAD] + sorted([i for i in ids if i != LEAD],
                              key=lambda m: -(row(m).PCE_SAScore_compl_FF065
                                              if not pd.isna(row(m).PCE_SAScore_compl_FF065)
                                              else -99))
    for mid in ordered:
        r = row(mid)
        pce = r.PCE_compl_FF065 if not pd.isna(r.PCE_compl_FF065) else r.PCE_strict_FF065
        ps065 = (r.PCE_SAScore_compl_FF065 if not pd.isna(r.PCE_SAScore_compl_FF065)
                 else r.PCE_SAScore_strict_FF065)
        psgrn = (r.PCE_SAScore_compl_FFgreen if not pd.isna(r.PCE_SAScore_compl_FFgreen)
                 else r.PCE_SAScore_strict_FFgreen)
        formula = "\\ch{" + str(r.formula) + "}"
        bold = mid == LEAD
        cells = [
            f"\\textbf{{{mid}}}" if bold else str(mid),
            formula,
            f"${fmt(r.HOMO_eV, 3, plus=True)}$",
            f"${fmt(r.LUMO_eV, 3, plus=True)}$",
            fmt(r.gap_eV, 3),
            fmt(r.SAScore, 2),
            fmt(pce, 2),
            f"${fmt(ps065, 2, plus=True)}$ (${fmt(psgrn, 2, plus=True)}$)",
            verdict[mid],
        ]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    (TABDIR / "tab_candidates.tex").write_text("\n".join(lines))
    print(f"  tab_candidates.tex      {len(ordered)} rows: {ordered}")


