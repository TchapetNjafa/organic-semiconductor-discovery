def tab_conventions():
    lines = [
        "% Regenerated by regen_tables.py. Ledger L-2026-09-01-17.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The screen under all four combinations of absorber convention and "
        "fill-factor expression. \\emph{Strict} requires the molecule's own gap to be the "
        "narrower of the pair; \\emph{complementary} admits any molecule absorbing in "
        "\\qtyrange{1.1}{2.2}{\\electronvolt}. The cascade counts molecules passing the "
        "physical gates, then the validity filter, then the stability screen, then "
        "$\\pcesascore > 0$. First place changes with the convention; the intersection of "
        "all four sets does not.}",
        "\\label{tab:conventions}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "convention & cascade & \\makecell{max PCE\\\\(\\unit{\\percent})} & first place \\\\",
        "\\midrule",
    ]
    for key, label in VARIANTS:
        kind = key.split("_")[0]
        pool = df[f"passes_{kind}"].astype(bool)
        valid = pool & df.chemically_valid.astype(bool)
        stable = valid & df.stable.astype(bool)
        pos = stable & (df[f"PCE_SAScore_{key}"] > 0)
        v = summary["variants"][key]
        first = v["first"]
        cascade = f"{int(pool.sum())} $\\to$ {int(valid.sum())} $\\to$ " \
                  f"{int(stable.sum())} $\\to$ {int(pos.sum())}"
        mark = f"\\textbf{{{first}}}" if first == LEAD else str(first)
        lines.append(f"{label} & {cascade} & {v['max_pce_all']:.2f} & {mark} \\\\")
    inter = ", ".join(str(i) for i in robust["intersection_all_variants"])
    lines += [
        "\\midrule",
        f"\\multicolumn{{4}}{{l}}{{intersection of all four sets: \\textbf{{{inter}}}}} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}", "",
    ]
    (TABDIR / "tab_conventions.tex").write_text("\n".join(lines))
    print(f"  tab_conventions.tex     4 variants, intersection {{{inter}}}")


